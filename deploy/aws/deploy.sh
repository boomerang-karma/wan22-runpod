#!/usr/bin/env bash
# Deploy Meme Studio (portal/) to AWS with Auth0 login. Needs only the AWS CLI: the image is built by CodeBuild.
#
#   deploy/aws/deploy.sh            create or update the stack, build the current working tree, roll it out
#   deploy/aws/deploy.sh --infra    apply settings and secrets only; keep the running image
#
# Settings come from deploy/aws/deploy.env (copy deploy.env.example); exported variables take precedence.
# Secrets (RunPod key, Auth0 client secret) go straight to Secrets Manager, never into the stack or its parameters.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
ENV_FILE=${ENV_FILE:-$HERE/deploy.env}
MODE=full
case "${1:-}" in
  --infra) MODE=infra ;;
  "") ;;
  *) echo "usage: $0 [--infra]" >&2; exit 2 ;;
esac

die() { echo "error: $*" >&2; exit 1; }
step() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

# ---- settings: deploy.env without overriding what is already exported (values cannot contain '#')
if [[ -f $ENV_FILE ]]; then
  while IFS= read -r line || [[ -n $line ]]; do
    line=${line%%#*}
    [[ $line =~ ^[[:space:]]*([A-Z0-9_]+)=(.*)$ ]] || continue
    key=${BASH_REMATCH[1]}; val=${BASH_REMATCH[2]}
    val="${val#"${val%%[![:space:]]*}"}"; val="${val%"${val##*[![:space:]]}"}"
    val=${val#\"}; val=${val%\"}; val=${val#\'}; val=${val%\'}
    eval "isset=\${$key+x}"
    [[ -z $isset ]] && export "$key=$val"
  done < "$ENV_FILE"
else
  echo "note: $ENV_FILE not found; using exported variables only (see deploy.env.example)"
fi

PY=${PYTHON:-$ROOT/.venv/bin/python}
[[ -x $PY ]] || PY=python3
REGION=${AWS_REGION:-$(command aws configure get region 2>/dev/null || true)}
REGION=${REGION:-us-east-1}
STACK=${STACK_NAME:-meme-studio}
aws() { command aws --region "$REGION" "$@"; }

[[ -n ${AUTH0_DOMAIN:-} ]] || die "set AUTH0_DOMAIN (deploy.env)"
[[ -n ${AUTH0_CLIENT_ID:-} ]] || die "set AUTH0_CLIENT_ID (deploy.env)"
AUTH0_DOMAIN=${AUTH0_DOMAIN#https://}; AUTH0_DOMAIN=${AUTH0_DOMAIN%/}

# RunPod endpoint and key: deploy.env, else the files wanctl.py uses
runpod_from_files() {
  "$PY" - "$ROOT" "$1" <<'EOF'
import sys
sys.path.insert(0, sys.argv[1])
import wanctl
cfg = wanctl.load_config(f"{sys.argv[1]}/config.yaml")
print({"endpoint": lambda: wanctl._endpoint_id(cfg), "key": lambda: wanctl.api_key(cfg),
       "dcs": lambda: ",".join(wanctl.data_centers(cfg))}[sys.argv[2]]())
EOF
}
RUNPOD_ENDPOINT_ID=${RUNPOD_ENDPOINT_ID:-$(runpod_from_files endpoint)} || die "no RunPod endpoint id"
RUNPOD_DATA_CENTERS=$(runpod_from_files dcs 2>/dev/null || true)

step "AWS account"
ACCOUNT=$(aws sts get-caller-identity --query Account --output text) || die "the AWS CLI is not signed in"
echo "account $ACCOUNT · region $REGION · stack $STACK · RunPod endpoint $RUNPOD_ENDPOINT_ID"
PREFIX_LIST=$(aws ec2 describe-managed-prefix-lists \
  --filters Name=prefix-list-name,Values=com.amazonaws.global.cloudfront.origin-facing \
  --query 'PrefixLists[0].PrefixListId' --output text)
[[ $PREFIX_LIST == pl-* ]] || die "could not find the CloudFront origin-facing prefix list in $REGION"

PARAMS=(
  "AppName=$STACK" "RunPodEndpointId=$RUNPOD_ENDPOINT_ID" "RunPodDataCenter=$RUNPOD_DATA_CENTERS"
  "Auth0Domain=$AUTH0_DOMAIN" "Auth0ClientId=$AUTH0_CLIENT_ID" "AllowedEmails=${ALLOWED_EMAILS:-}"
  "DailyBudgetUsd=${DAILY_BUDGET_USD:-5}" "UserDailyBudgetUsd=${USER_DAILY_BUDGET_USD:-1}"
  "MaxActive=${MAX_ACTIVE:-3}" "UserMaxActive=${USER_MAX_ACTIVE:-2}"
  "CloudFrontPrefixListId=$PREFIX_LIST" "DomainName=${DOMAIN_NAME:-}" "CertificateArn=${CERTIFICATE_ARN:-}"
  "TaskCpu=${TASK_CPU:-512}" "TaskMemory=${TASK_MEMORY:-1024}"
)
deploy_stack() {   # image tag, desired count
  aws cloudformation deploy --stack-name "$STACK" --template-file "$HERE/template.yaml" \
    --capabilities CAPABILITY_IAM --no-fail-on-empty-changeset \
    --parameter-overrides "${PARAMS[@]}" "ImageTag=$1" "DesiredCount=$2"
}
output() {
  aws cloudformation describe-stacks --stack-name "$STACK" \
    --query "Stacks[0].Outputs[?OutputKey=='$1'].OutputValue" --output text
}

STATUS=$(aws cloudformation describe-stacks --stack-name "$STACK" --query 'Stacks[0].StackStatus' \
  --output text 2>/dev/null || echo NONE)
case $STATUS in
  ROLLBACK_COMPLETE) die "stack $STACK failed to create earlier; delete it (deploy/aws/destroy.sh) and run again" ;;
  *_IN_PROGRESS) die "stack $STACK is busy ($STATUS); wait for it to finish" ;;
esac
CURRENT_TAG=none
if [[ $STATUS == NONE ]]; then
  step "Creating the stack (network, storage, registry, build project, CloudFront): about 5-10 minutes"
  deploy_stack none 0
else
  CURRENT_TAG=$(aws cloudformation describe-stacks --stack-name "$STACK" \
    --query "Stacks[0].Parameters[?ParameterKey=='ImageTag'].ParameterValue" --output text)
fi

# ---- secrets: merge into the stack's secret (SESSION_SECRET was generated by CloudFormation)
step "Secrets Manager"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
chmod 700 "$TMP"
RUNPOD_API_KEY=${RUNPOD_API_KEY:-$(runpod_from_files key)} || die "no RunPod API key"
SECRET_ARN=$(output AppSecretArn)
aws secretsmanager get-secret-value --secret-id "$SECRET_ARN" --query SecretString --output text > "$TMP/secret.json"
SECRETS_CHANGED=$(RUNPOD_API_KEY="$RUNPOD_API_KEY" AUTH0_CLIENT_SECRET="${AUTH0_CLIENT_SECRET:-}" \
  "$PY" - "$TMP/secret.json" <<'EOF'
import json, os, sys
path = sys.argv[1]
d = json.load(open(path))
changed = False
for k in ("RUNPOD_API_KEY", "AUTH0_CLIENT_SECRET"):
    v = os.environ.get(k, "").strip()
    if v and d.get(k) != v:
        d[k], changed = v, True
missing = [k for k in ("RUNPOD_API_KEY", "AUTH0_CLIENT_SECRET") if not d.get(k)]
if missing:
    sys.exit("missing secrets (set them in deploy.env or export them): " + ", ".join(missing))
json.dump(d, open(path, "w"))
print("yes" if changed else "no")
EOF
) || die "secrets incomplete"
if [[ $SECRETS_CHANGED == yes ]]; then
  aws secretsmanager put-secret-value --secret-id "$SECRET_ARN" --secret-string "file://$TMP/secret.json" >/dev/null
  echo "updated RUNPOD_API_KEY / AUTH0_CLIENT_SECRET"
else
  echo "unchanged"
fi

if [[ $MODE == infra ]]; then
  [[ $CURRENT_TAG != none ]] || die "nothing built yet; run without --infra first"
  step "Applying settings (image $CURRENT_TAG)"
  deploy_stack "$CURRENT_TAG" 1
  if [[ $SECRETS_CHANGED == yes ]]; then          # running tasks read secrets only at start
    aws ecs update-service --cluster "$(output ClusterName)" --service "$(output ServiceName)" \
      --force-new-deployment >/dev/null
  fi
else
  # ---- build: zip exactly what the image needs from the working tree, CodeBuild builds and pushes it
  step "Building the image in CodeBuild (ARM64): about 3-5 minutes"
  TAG="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo build)-$(date -u +%Y%m%d%H%M%S)"
  "$PY" - "$ROOT" "$TMP/portal.zip" <<'EOF'
import os, sys, zipfile
root, out = sys.argv[1], sys.argv[2]
files = ["wanctl.py", "config.example.yaml"]
for d, dirs, names in os.walk(os.path.join(root, "portal")):
    dirs[:] = [x for x in dirs if x != "__pycache__"]
    files += [os.path.relpath(os.path.join(d, n), root) for n in names if not n.endswith(".pyc")]
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    for f in sorted(files):
        z.write(os.path.join(root, f), f)
print(f"{len(files)} files")
EOF
  aws s3 cp "$TMP/portal.zip" "s3://$(output SourceBucketName)/source/portal.zip" --only-show-errors
  BUILD_ID=$(aws codebuild start-build --project-name "$(output BuildProject)" \
    --environment-variables-override "name=IMAGE_TAG,value=$TAG,type=PLAINTEXT" --query build.id --output text)
  LAST=""
  while :; do
    read -r BSTATUS PHASE < <(aws codebuild batch-get-builds --ids "$BUILD_ID" \
      --query 'builds[0].[buildStatus,currentPhase]' --output text)
    [[ "$PHASE" != "$LAST" ]] && { echo "  $PHASE"; LAST=$PHASE; }
    [[ $BSTATUS == IN_PROGRESS ]] || break
    sleep 10
  done
  [[ $BSTATUS == SUCCEEDED ]] || die "image build $BSTATUS; logs: aws logs tail /codebuild/$STACK --region $REGION"
  echo "pushed $(output RepositoryUri):$TAG"

  step "Rolling out $TAG (the old task stops first: about a minute of downtime)"
  deploy_stack "$TAG" 1
fi

step "Waiting for the app to become healthy"
aws ecs wait services-stable --cluster "$(output ClusterName)" --services "$(output ServiceName)" \
  || die "the service did not settle; logs: aws logs tail /ecs/$STACK --region $REGION --since 15m"

URL=$(output AppUrl)
cat <<EOF

Meme Studio is live: $URL

In the Auth0 dashboard -> Applications -> (your app) -> Settings, make sure these are set:
  Allowed Callback URLs   $(output Auth0CallbackUrl)
  Allowed Logout URLs     $(output Auth0LogoutUrl)
  Allowed Web Origins     $URL
EOF
if [[ -n ${DOMAIN_NAME:-} ]]; then
  echo
  echo "DNS: CNAME $DOMAIN_NAME -> $(output CloudFrontDomain)"
fi
echo
echo "Logs: aws logs tail /ecs/$STACK --region $REGION --follow"
